/** Polish plural: one (1), few (2–4, but not 12–14), many (everything else). */
const odm = (n: number, one: string, few: string, many: string) => {
  const j = n % 10, d = n % 100;
  if (n === 1) return one;
  return j >= 2 && j <= 4 && (d < 12 || d > 14) ? few : many;
};

